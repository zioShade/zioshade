/// Prewrite a unique emitted name for every OpTypeStruct into `names` BEFORE any
/// struct forward-decl emission. The forward-decl emitter dedups by NAME, so two
/// distinct structs sharing one OpName would otherwise collapse: the second's
/// real layout is dropped and its uses compile against the first -- silently
/// binding the wrong bytes (plausible-but-wrong, #zm0). This pass mangles
/// colliding names `S -> S_1 -> S_2` (matching spirv-cross) so every distinct
/// type keeps its own declaration. `sanitize_fn(name)` returns the target-
/// language form of a name (identity for GLSL, hlslSafeName for HLSL); mangling
/// runs on the sanitized form so two raw names that sanitize equal also split.
/// Only colliding types are mutated in `names` -- the common non-colliding path
/// is untouched. Run ONCE, after collectNames and before the first struct
/// forward-decl emission.
pub fn commonPrewriteUniqueStructNames(
    instructions: anytype,
    names: *std.AutoHashMap(u32, []const u8),
    alloc: std.mem.Allocator,
    comptime sanitize_fn: anytype,
) void {
    var taken = std.StringHashMap(void).init(alloc);
    defer taken.deinit();
    for (instructions) |inst| {
        if (inst.op != .TypeStruct) continue;
        const tid = resultIdFromOp(inst.op, inst.words) orelse continue;
        const base = sanitize_fn(names.get(tid) orelse "Struct");
        if (taken.get(base) == null) {
            taken.put(base, {}) catch {};
            continue;
        }
        var n: u32 = 1;
        while (true) : (n += 1) {
            const cand = std.fmt.allocPrint(alloc, "{s}_{d}", .{ base, n }) catch break;
            if (taken.get(cand) == null) {
                taken.put(cand, {}) catch {};
                names.put(tid, cand) catch {};
                break;
            }
        }
    }
}

/// For each FUNCTION-SCOPE id -- an `OpVariable` in the Function storage class,
/// or an `OpFunctionParameter` -- whose emitted name collides with a GLOBAL
/// variable's emitted name, mangle the local/param (`a_b -> a_b_1`) so it
/// cannot silently shadow the global (#sid). A function-scope id sharing a
/// global's name shadows it within the function, so an `OpLoad` of the global
/// reads the local/param instead -- plausible-but-wrong.
///
/// SCOPE-AWARE (the point): ONLY function-scope-vs-global collisions cause a
/// silent shadow, so ONLY those are mangled. Same-scope local/local collisions
/// are loud redefinitions the target compiler catches; type/type and
/// type/variable name overlaps (e.g. a UBO struct type and its instance both
/// `OpName "Globals"`) are handled by the backends' existing block naming and
/// are left alone. A broader all-OpName uniqueness pass regressed exactly those.
///
/// BLOCK-INSTANCE EXCLUSION: a GLSL UBO instance (Uniform storage class, pointee
/// a `Block`-decorated -- NOT `BufferBlock` -- struct) is emitted under a
/// block-naming-mangled name (e.g. `Globals_1`), NOT its raw OpName, so a
/// function-local sharing the block's raw OpName does NOT shadow it. Such UBO
/// instances are excluded from the collision set; without this, the local would
/// be mangled INTO the block-naming suffix space and collide with the instance.
/// SSBOs (StorageBuffer+Block, or Uniform+BufferBlock) are emitted under their
/// RAW instance name, so they STAY in the collision set (a local CAN shadow
/// them). PushConstants: GLSL emits them bare (stay in the set) and HLSL
/// honest-errors, but MSL block-names them name_1 (like UBOs), so `exclude_push_constant`
/// is true only for MSL -- the sole backend for which they are excluded. (The
/// other backends don't _1-mangle UBOs and don't emit a collidable instance
/// name, so excluding their UBO instances is moot.)
///
/// Run ONCE after collectNames (and after the struct-name pre-pass). Only
/// colliding function-scope ids are mutated.
pub fn commonPrewriteUniqueLocalVarNames(
    instructions: anytype,
    names: *std.AutoHashMap(u32, []const u8),
    alloc: std.mem.Allocator,
    exclude_push_constant: bool,
) void {
    // block-only struct ids vs BufferBlock struct ids (distinguish UBO from SSBO),
    // and pointer-type id -> pointee type id.
    var block_only = std.AutoHashMap(u32, void).init(alloc);
    defer block_only.deinit();
    var buffer_block_types = std.AutoHashMap(u32, void).init(alloc);
    defer buffer_block_types.deinit();
    var pointee_of = std.AutoHashMap(u32, u32).init(alloc);
    defer pointee_of.deinit();
    for (instructions) |inst| {
        switch (inst.op) {
            .Decorate => if (inst.words.len >= 3) {
                const dec = @as(spirv.Decoration, @enumFromInt(inst.words[2]));
                if (dec == .block) block_only.put(inst.words[1], {}) catch {};
                if (dec == .buffer_block) buffer_block_types.put(inst.words[1], {}) catch {};
            },
            .TypePointer => if (inst.words.len >= 4) pointee_of.put(inst.words[1], inst.words[3]) catch {},
            else => {},
        }
    }

    // Names claimed by global (non-Function) variables, EXCLUDING GLSL UBO
    // instances (Uniform + Block-not-BufferBlock pointee: emitted as Globals_1,
    // so a local with the block's raw OpName does not shadow them).
    var claimed = std.StringHashMap(void).init(alloc);
    defer claimed.deinit();
    for (instructions) |inst| {
        if (inst.op != .Variable or inst.words.len < 4) continue;
        const sc = @as(spirv.StorageClass, @enumFromInt(inst.words[3]));
        if (sc == .Function) continue;
        if (sc == .Uniform) {
            if (pointee_of.get(inst.words[1])) |pointee| {
                if (block_only.contains(pointee) and !buffer_block_types.contains(pointee)) continue;
            }
        } else if (exclude_push_constant and sc == .PushConstant) {
            // MSL also block-names PushConstant instances (constant T& name_1, like
            // UBOs), so a local sharing the block's raw OpName does not shadow them.
            // GLSL emits PushConstants under their raw instance name and HLSL
            // honest-errors on them, so only MSL passes exclude_push_constant=true.
            continue;
        }
        if (names.get(inst.words[2])) |nm| claimed.put(nm, {}) catch {};
    }

    // Mangle function-scope ids (Function-class OpVariable or OpFunctionParameter)
    // whose name collides with a claimed global. (0 is never a valid SPIR-V id.)
    for (instructions) |inst| {
        const vid: u32 = blk: {
            switch (inst.op) {
                .Variable => {
                    if (inst.words.len < 4) break :blk 0;
                    if (@as(spirv.StorageClass, @enumFromInt(inst.words[3])) != .Function) break :blk 0;
                    break :blk inst.words[2];
                },
                .FunctionParameter => break :blk if (inst.words.len >= 3) inst.words[2] else 0,
                else => break :blk 0,
            }
        };
        if (vid == 0) continue;
        const base = names.get(vid) orelse continue;
        if (claimed.get(base) == null) continue; // no collision -> untouched
        var n: u32 = 1;
        while (true) : (n += 1) {
            const cand = std.fmt.allocPrint(alloc, "{s}_{d}", .{ base, n }) catch break;
            if (claimed.get(cand) == null) {
                names.put(vid, cand) catch {};
                claimed.put(cand, {}) catch {}; // claim -> two colliding locals differ
                break;
            }
        }
    }
}

/// Get array dimension suffix for a pointer type. E.g., "[4]" or "[2][3]" for multi-dim.
/// HLSL uses multi_dim=true to unwrap nested TypeArray layers.
/// Takes instruction slice + id_defs to work across different ParsedModule types.
pub fn commonGetArraySuffix(instructions: anytype, id_defs: anytype, ptr_type_id: u32, multi_dim: bool) ![]const u8 {
    const ptr_inst = localGetDef(instructions, id_defs, ptr_type_id) orelse return "";
    if (ptr_inst.op != .TypePointer or ptr_inst.words.len <= 3) return "";

    if (!multi_dim) {
        const pointee_id = ptr_inst.words[3];
        const pt_inst = localGetDef(instructions, id_defs, pointee_id) orelse return "";
        if (pt_inst.op == .TypeArray and pt_inst.words.len > 3) {
            const len_id = pt_inst.words[3];
            const len_def = localGetDef(instructions, id_defs, len_id);
            if (len_def) |ld| {
                // OpSpecConstant has the same word layout as OpConstant (words[3] = the
                // literal default), so a spec-constant-length array specializes to its
                // default size — a valid compile-time dimension. (OpSpecConstantOp is
                // excluded: words[3] is an opcode, not a literal.) #475
                if ((ld.op == .Constant or ld.op == .SpecConstant) and ld.words.len > 3) {
                    var buf: [32]u8 = undefined;
                    const s = std.fmt.bufPrint(&buf, "[{d}]", .{ld.words[3]}) catch return "";
                    return try std.heap.page_allocator.dupe(u8, s);
                }
            }
        }
        return "";
    }

    // Multi-dimension path (HLSL): collect all nested TypeArray dimensions
    var dims: [4]u32 = undefined;
    var dim_count: usize = 0;
    var current_id = ptr_inst.words[3];
    while (dim_count < dims.len) {
        const pt_inst = localGetDef(instructions, id_defs, current_id) orelse break;
        if (pt_inst.op != .TypeArray or pt_inst.words.len <= 3) break;
        const len_id = pt_inst.words[3];
        const len_def = localGetDef(instructions, id_defs, len_id);
        if (len_def) |ld| {
            if ((ld.op == .Constant or ld.op == .SpecConstant) and ld.words.len > 3) {
                dims[dim_count] = ld.words[3];
                dim_count += 1;
            } else break;
        } else break;
        current_id = pt_inst.words[2];
    }
    if (dim_count == 0) return "";

    var buf: [64]u8 = undefined;
    var pos: usize = 0;
    for (dims[0..dim_count]) |d| {
        const part = std.fmt.bufPrint(buf[pos..], "[{d}]", .{d}) catch break;
        pos += part.len;
    }
    const suffix = buf[0..pos];
    return try std.heap.page_allocator.dupe(u8, suffix);
}

pub fn localGetDef(instructions: anytype, id_defs: anytype, id: u32) ?@TypeOf(instructions[0]) {
    const idx = if (id < id_defs.len) id_defs[id] orelse return null else return null;
    if (idx >= instructions.len) return null;
    return instructions[idx];
}

/// Resolve an OpTypeArray length id to a concrete u32 for backends that have no
/// specialization constants (HLSL/GLSL/MSL). OpConstant/OpSpecConstant -> their
/// literal/default (words[3]); OpSpecConstantOp -> evaluated using operand defaults
/// (IAdd/ISub/IMul of leaf constants, e.g. `const int d = c + 50;` -> c's default
/// + 50). Returns null for shapes it can't evaluate so the caller can honest-error
/// rather than emit a wrong size. `module` is anytype (HLSL's own ParsedModule
/// shares the .instructions/.id_defs shape).
pub fn arrayLengthValue(module: anytype, len_id: u32) ?u32 {
    return arrayLenEval(module, len_id, 0);
}
fn arrayLenEval(module: anytype, len_id: u32, depth: u32) ?u32 {
    if (depth > 8) return null;
    const def = localGetDef(module.instructions, module.id_defs, len_id) orelse return null;
    switch (def.op) {
        .Constant, .SpecConstant => return if (def.words.len > 3) def.words[3] else null,
        .SpecConstantOp => {
            // words layout: [hdr, result_type, result_id, opcode, operand1, operand2, ...]
            if (def.words.len < 6) return null;
            const oc = def.words[3];
            const a = arrayLenEval(module, def.words[4], depth + 1) orelse return null;
            const b = arrayLenEval(module, def.words[5], depth + 1) orelse return null;
            if (oc == @intFromEnum(spirv.Op.IAdd)) return a +% b;
            if (oc == @intFromEnum(spirv.Op.ISub)) return a -% b;
            if (oc == @intFromEnum(spirv.Op.IMul)) return a *% b;
            return null;
        },
        else => return null,
    }
}

