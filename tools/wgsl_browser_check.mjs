#!/usr/bin/env node
// WGSL BROWSER render oracle: execute zioshade's WGSL output in a REAL consumer
// WebGPU stack (Chrome + tint + Dawn, rasterized by SwiftShader) and diff the
// render against the Metal-proxy reference the wgsl-render gate uses.
//
// WHY THIS ORACLE EXISTS. The existing WGSL render proxy (tools/wgsl_render_check.sh)
// validates the WGSL by round-tripping naga -> SPIR-V -> spirv-cross MSL -> Metal. That
// confound was blind to the live P1 of bead zioshade-8k2: Chrome/tint REJECTED zioshade's
// WGSL at pipeline build ("textureSample must only be called from uniform control flow")
// while naga accepted it, so every text gate and every proxy gate passed and the wintty.io
// player silently fell back to black. Only a consumer stack (the real tint frontend, the
// real Dawn pipeline + binding validation, a real rasterizer) can see BOTH classes:
//   REJECT  tint/Dawn refuses the pipeline (the 8k2 class; surfaced with the verbatim
//           validation/compilation message)
//   FAIL    the pipeline builds, the shader runs, but the pixels are wrong (incl. the
//           silent-black fallback: black where the reference has content)
//
// HOW IT WORKS. Per shader, in one browser that stays up for the whole sweep:
//   1. source GLSL ->(glslang)-> src.spv
//   2. src.spv ->(zioshade wgsl)-> z.wgsl            [the output under test]
//   3. src.spv ->(spirv-cross --msl)-> ref.msl ->(ShaderCompare on Metal)-> reference PPM
//      (the same reference leg tools/wgsl_render_check.sh uses; ShaderCompare is invoked
//      with the SAME file on both legs so its _zioshade.ppm output IS the reference
//      render, generated by exactly the code path the proxy gate compares against)
//   4. z.wgsl -> the harness page (tools/wgsl_browser_harness.html) -> 3 frames on a
//      256x256 WebGPU canvas -> PAGE SCREENSHOT of the canvas element (WebGPU canvases
//      read back black via drawImage, so the screenshot is the only honest readback)
//      -> PNG decoded in-process (no dependencies; minimal 8-bit RGB/RGBA decoder)
//   5. pixel diff vs the reference (RGB, per channel)
//
// DETERMINISTIC UNIFORM STATE (single state for EVERY corpus, chosen once):
// the ShaderCompare GALLERY set at 256x256, because mid-animation cursor values
// matter (with the historical zero-cursor set the mode-change shaders short-circuit
// to their static path and their bug shapes never execute):
//     iResolution=(256,256,1)  iTime=1.7  iTimeDelta=1/60  iFrameRate=60  iFrame=102
//     iChannelTime[4]=0        iChannelResolution[4]=(256,256,1) each
//     iMouse=(64,64,64,64)     iDate=(2026,8,22,43200)    iSampleRate=48000
//     iCurrentCursor=(49,78,9,18)  iPreviousCursor=(159,122,18,18)   [a move in flight:
//         (iTime - iTimeCursorChange)/DURATION = 0.1, peak trail, the WARP-harness state]
//     cursor colors=(0.24,0.78,0.94,1)  styles=(0,0)  iCursorVisible=1
//     iTimeCursorChange=1.68  iTimeFocus=5.0  iFocus=1
//     iPalette[256] = HSV-ish ramp t=i/255 -> (t, tri(t), 1-t)
//     bg=(0.08,0.08,0.10) fg=(0.85,0.87,0.90) cursor=(0.24,0.78,0.94) cursorText=(0,0,0)
//     selFg=(1,1,1) selBg=(0.25,0.35,0.50)
//   iChannel0 = the ShaderCompare 256x256 reference texture (r=x*255/w, g=y*255/h,
//   b=(x^y)&255, integer division), linear/linear sampler.
//
// VERDICTS:
//   PASS        pipeline built, 3 frames rendered, diff within thresholds
//   REJECT      tint/Dawn refused (pipeline validation error or compile-info error);
//               the verbatim message is printed  [the 8k2 class]
//   FAIL        rendered but pixels diverge beyond thresholds, or the page died
//   LIVE-PASS   no reference available (ZWB_NO_REFERENCE=1, or the reference leg failed
//               for this shader): pipeline built + frames rendered + non-black coverage;
//               CLEARLY WEAKER, labeled as such (still catches every REJECT)
//   SKIP-*      the WGSL itself could not be produced (glslang refused the source
//               outside the gallery corpus, or a zioshade honest error)
//
// CROSS-GPU EPSILON. The proxy gate compares Metal-vs-Metal (maxdiff <= 1). This oracle
// compares SwiftShader-vs-Metal, so pure FP-ordering noise is wider; the thresholds below
// (MAXDIFF_PASS / BADPIX_PCT_PASS) were measured on the gallery corpus: benign
// cross-GPU divergence stays far below them, while the black-output negative control
// exceeds them by an order of magnitude.
//
// MODES / ENV:
//   ZWB_NO_REFERENCE=1       skip the Metal reference leg entirely; every shader is
//                            judged by the weaker LIVE-PASS assertions (loud banner)
//   ZWB_OVERRIDE_DIR=<dir>   per-shader negative control: if <dir>/<name>.wgsl exists,
//                            THAT text is rendered instead of the freshly compiled
//                            output (how the "broken WGSL must FAIL" proof is run; the
//                            staged outputs land in the share dir to hand-edit)
//   ZWB_SHARE=<dir>          staging + artifacts (default /tmp/zioshade_wgsl_browser);
//                            per shader: *.g.frag *.src.spv *.z.wgsl *.ref.msl
//                            *.shot.png (the screenshot) and *.browser.ppm (decoded)
//   ZWB_PLAYWRIGHT=<module>  playwright import path (default: bare 'playwright', then
//                            the known local install)
//   ZWB_CHROME=<path>        Chrome for Testing executable (the headless shell has no
//                            WebGPU; a full Chrome is required)
//
// SOURCE LEG: src.spv comes from glslang, an oracle independent of zioshade's
// frontend, for every corpus including the gallery. Gallery sources must compile
// under glslang verbatim (the corpus README invariant): a refusal there is a
// broken gallery entry and fails the gate, never a reason to stage the source
// through zioshade's own frontend (that lower-rigor leg would silently absorb
// the next real refusal into a frontend-correlated comparison). Outside the
// gallery corpus a glslang refusal stays a plain skip-glslang.
//
// BASELINE / GATE semantics (same style as tools/wgsl_render_baseline.txt):
// expected REJECT/FAIL entries are pinned in tools/wgsl_browser_baseline.txt, one per
// line, format "<corpus-dir>/<name>.frag: <reason>"; every entry MUST cite a reason.
// Exit 0 when every REJECT/FAIL is pinned, 1 on any NEW one. Regenerate with
// --update-baseline. The expectation for the gallery is 16/16 PASS with an EMPTY
// baseline; an entry there is a consumer-corpus regression.
//
// USAGE:
//   node tools/wgsl_browser_check.mjs [corpus dirs ...]   (default tests/wintty_gallery)
//   node tools/wgsl_browser_check.mjs --update-baseline [dirs]
//   node tools/wgsl_browser_check.mjs tests/wintty_gallery tools/wgsl_browser_fixtures
//
// NOT CI-SAFE: needs Chrome for Testing, a playwright import, node, and (for the
// reference leg) swiftc + Metal + glslang + spirv-cross. Manual only (`just wgsl-browser`).

