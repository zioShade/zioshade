function die(msg) {
  console.error("error: " + msg);
  process.exit(2);
}

function run(cmd, args, opts = {}) {
  const r = spawnSync(cmd, args, { encoding: "buffer", maxBuffer: 1 << 28, ...opts });
  return { ok: r.status === 0, r };
}

function onPath(tool) {
  return spawnSync("/usr/bin/which", [tool]).status === 0;
}

const mtime = (p) => {
  try { return statSync(p).mtimeMs; } catch { return 0; }
};

// the proxy's layout rewrite: location-qualify the output declaration
function stageFragSource(srcPath, dstPath) {
  const text = readFileSync(srcPath, "utf8");
  writeFileSync(dstPath, text.replace(/^(out [a-z0-9]*vec4 [A-Za-z_][A-Za-z0-9_]*;)/m, "layout(location=0) $1"));
}

// ---------------------------------------------------------------------------
// PNG decode (8-bit RGB/RGBA, non-interlaced; the subset Chrome screenshots use)
// ---------------------------------------------------------------------------

function decodePng(buf) {
  const SIG = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);
  if (buf.length < 8 || !buf.subarray(0, 8).equals(SIG)) throw new Error("not a PNG");
  let pos = 8;
  let w = 0, h = 0, bitDepth = 0, colorType = 0, interlace = 0;
  const idat = [];
  while (pos + 12 <= buf.length) {
    const len = buf.readUInt32BE(pos);
    const type = buf.toString("ascii", pos + 4, pos + 8);
    const data = buf.subarray(pos + 8, pos + 8 + len);
    pos += 12 + len;
    if (type === "IHDR") {
      w = data.readUInt32BE(0); h = data.readUInt32BE(4);
      bitDepth = data[8]; colorType = data[9]; interlace = data[12];
    } else if (type === "IDAT") idat.push(data);
    else if (type === "IEND") break;
  }
  if (bitDepth !== 8) throw new Error("unsupported PNG bit depth " + bitDepth);
  if (colorType !== 2 && colorType !== 6) throw new Error("unsupported PNG color type " + colorType);
  if (interlace) throw new Error("interlaced PNG unsupported");
  const bpp = colorType === 6 ? 4 : 3;
  const stride = w * bpp;
  const raw = inflateSync(Buffer.concat(idat));
  if (raw.length < h * (stride + 1)) throw new Error("truncated PNG data");
  const px = Buffer.alloc(w * h * 4);
  let prev = Buffer.alloc(stride);
  let p = 0;
  for (let y = 0; y < h; y++) {
    const filter = raw[p++];
    const cur = Buffer.from(raw.subarray(p, p + stride)); // copy: defilter in place
    p += stride;
    for (let x = 0; x < stride; x++) {
      const a = x >= bpp ? cur[x - bpp] : 0;
      const b = prev[x];
      const c = x >= bpp ? prev[x - bpp] : 0;
      let v = cur[x];
      if (filter === 1) v = (v + a) & 255;
      else if (filter === 2) v = (v + b) & 255;
      else if (filter === 3) v = (v + ((a + b) >> 1)) & 255;
      else if (filter === 4) {
        const pa = Math.abs(b - c), pb = Math.abs(a - c), pc = Math.abs(a + b - 2 * c);
        const pr = pa <= pb && pa <= pc ? a : pb <= pc ? b : c;
        v = (v + pr) & 255;
      } else if (filter !== 0) throw new Error("bad PNG filter " + filter);
      cur[x] = v;
    }
    for (let x = 0; x < w; x++) {
      const o = (y * w + x) * 4;
      px[o] = cur[x * bpp]; px[o + 1] = cur[x * bpp + 1]; px[o + 2] = cur[x * bpp + 2];
      px[o + 3] = bpp === 4 ? cur[x * bpp + 3] : 255;
    }
    prev = cur;
  }
  return { w, h, px };
}

// P3 (ASCII) PPM, what ShaderCompare saves
function parsePpm(text) {
  const tok = text.trim().split(/\s+/);
  if (tok[0] !== "P3") throw new Error("not a P3 PPM");
  const w = parseInt(tok[1], 10), h = parseInt(tok[2], 10);
  const n = w * h * 3;
  if (tok.length < 4 + n) throw new Error("truncated PPM");
  const px = Buffer.alloc(n);
  for (let i = 0; i < n; i++) px[i] = parseInt(tok[4 + i], 10) & 255;
  return { w, h, px };
}

// RGB diff of an RGBA buffer against an RGB reference
function compare(rgba, ref) {
  const n = rgba.w * rgba.h;
  let maxDiff = 0, sum = 0, bad = 0;
  for (let i = 0; i < n; i++) {
    const a = i * 4, b = i * 3;
    let pd = 0;
    for (let c = 0; c < 3; c++) {
      const d = Math.abs(rgba.px[a + c] - ref.px[b + c]);
      if (d > maxDiff) maxDiff = d;
      sum += d;
      if (d > pd) pd = d;
    }
    if (pd > 16) bad++;
  }
  return { maxDiff, avgDiff: sum / (n * 3), badPct: (100 * bad) / n };
}

function nonBlackPct(rgba) {
  let n = 0;
  for (let i = 0; i < rgba.w * rgba.h; i++) {
    const o = i * 4;
    if (rgba.px[o] > 10 || rgba.px[o + 1] > 10 || rgba.px[o + 2] > 10) n++;
  }
  return (100 * n) / (rgba.w * rgba.h);
}

