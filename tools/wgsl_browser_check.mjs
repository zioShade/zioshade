async function sweep(cases) {
  const pw = await loadPlaywright();
  let current = "";
  const server = createServer((req, res) => {
    if (req.url === "/case") {
      res.writeHead(200, { "content-type": "application/json" });
      res.end(JSON.stringify({ wgsl: current }));
      return;
    }
    res.writeHead(200, { "content-type": "text/html" });
    res.end(readFileSync(HARNESS));
  });
  await new Promise((r) => server.listen(0, "127.0.0.1", r));
  const url = "http://127.0.0.1:" + server.address().port + "/";

  const browser = await pw.chromium.launch({
    executablePath: CHROME,
    headless: true,
    args: ["--enable-unsafe-webgpu", "--enable-features=Vulkan", "--use-angle=swiftshader"],
  });
  const context = await browser.newContext({ viewport: { width: 420, height: 420 }, deviceScaleFactor: 1 });

  const results = [];
  try {
    for (const c of cases) {
      current = c.wgsl;
      const page = await context.newPage();
      const consoleLines = [];
      page.on("console", (m) => {
        if (m.type() === "error" || m.type() === "warning") consoleLines.push(m.type() + ": " + m.text());
      });
      page.on("pageerror", (e) => consoleLines.push("pageerror: " + e.message));
      const res = { reject: null, fail: null, img: null, frames: 0, adapter: null, console: null };
      try {
        await page.goto(url, { waitUntil: "domcontentloaded" });
        const handle = await page.waitForFunction(
          () => {
            if (window.__zwb && window.__zwb.settled) return window.__zwb;
            return false;
          },
          null,
          { polling: 100, timeout: 120000 },
        );
        const st = await handle.jsonValue();
        if (st.adapterInfo) {
          const ai = st.adapterInfo;
          res.adapter = [ai.vendor, ai.architecture].filter(Boolean).join("/") || "unknown";
        }
        if (st.fatal) {
          res.fail = "harness fatal: " + st.fatal;
        } else if (st.pipelineError || (st.compileErrors && st.compileErrors.length)) {
          const parts = [];
          if (st.pipelineError) parts.push(st.pipelineError);
          for (const m of st.compileErrors || []) parts.push("compile " + m);
          res.reject = parts.join(" | ");
        } else {
          const shot = await page.locator("#c").screenshot();
          writeFileSync(c.d + ".shot.png", shot);
          const img = decodePng(shot);
          if (img.w !== RES || img.h !== RES) {
            res.fail = "screenshot is " + img.w + "x" + img.h + ", expected " + RES + "x" + RES;
          } else {
            res.img = img;
            res.frames = st.framesRendered;
            // persist the decoded render next to the reference for debugging
            let ppm = "P3\n" + RES + " " + RES + "\n255\n";
            for (let y = 0; y < RES; y++) {
              const row = [];
              for (let x = 0; x < RES; x++) {
                const o = (y * RES + x) * 4;
                row.push(img.px[o] + " " + img.px[o + 1] + " " + img.px[o + 2]);
              }
              ppm += row.join(" ") + "\n";
            }
            writeFileSync(c.d + ".browser.ppm", ppm);
          }
        }
      } catch (e) {
        res.fail = "driver error: " + (e && e.message ? e.message : String(e));
      }
      if (consoleLines.length) res.console = consoleLines;
      results.push(res);
      await page.close();
    }
  } finally {
    await browser.close();
    server.close();
  }
  return results;
}

