  const c = staged[i];
  const r = browserResults[i];
  let verdict, line = "";
  if (r.reject) {
    verdict = "REJECT";
    line = r.reject;
  } else if (r.fail) {
    verdict = "FAIL";
    line = r.fail;
  } else if (c.ref) {
    const m = compare(r.img, c.ref);
    line = "max=" + m.maxDiff + " avg=" + m.avgDiff.toFixed(4) + " bad=" + m.badPct.toFixed(3) + "%";
    if (m.maxDiff <= MAXDIFF_PASS && m.badPct <= BADPIX_PCT_PASS) verdict = "PASS";
    else {
      verdict = "FAIL";
      line += " (thresholds " + MAXDIFF_PASS + "/" + BADPIX_PCT_PASS + "%)";
    }
  } else {
    const nb = nonBlackPct(r.img);
    verdict = nb >= LIVE_NONBLACK_MIN && r.frames === 3 ? "LIVE-PASS" : "FAIL";
    line = "nonblack=" + nb.toFixed(1) + "% frames=" + r.frames + " [WEAKER: no reference]";
  }
  bump(verdict);
  console.log("  " + verdict.padEnd(9) + " " + c.key + "  " + line);
  if (verdict === "REJECT" || verdict === "FAIL") fails.push({ key: c.key, verdict, line });
