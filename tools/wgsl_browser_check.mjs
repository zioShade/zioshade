// ---------------------------------------------------------------------------
// stage + reference generation (mirror of the proxy's legs)
// ---------------------------------------------------------------------------

function stageShader(dir, name) {
  const alias = path.basename(dir);
  const d = path.join(SHARE, alias + "." + name);
  stageFragSource(inRoot(dir) + "/" + name + ".frag", d + ".g.frag");
  const out = { key: dir + "/" + name + ".frag", d, wgsl: null, ref: null, skip: null, overridden: false, refused: false };

  const g = run("glslangValidator", ["-V", "-S", "frag", d + ".g.frag", "-o", d + ".src.spv"]);
  if (!g.ok) {
    // A gallery source glslang refuses is a broken gallery entry, not a
    // compiler verdict: it fails the gate loudly (see the staging loop)
    // instead of being skipped, pinned, or staged through a lower-rigor
    // source leg. Other corpora keep the historical skip.
    if (/wintty_gallery/.test(dir)) {
      out.refused = true;
    } else {
      out.skip = "skip-glslang";
    }
    return out;
  }

  const w = run(CLI, ["wgsl", d + ".src.spv", "--stage", "fragment"]);
  if (!w.ok) { out.skip = "skip-zwgsl"; return out; }
  out.wgsl = w.r.stdout.toString("utf8");
  writeFileSync(d + ".z.wgsl", out.wgsl);

  // negative-control hook: a hand-edited staged output replaces the compiled one
  if (overrideDir) {
    const ov = path.join(overrideDir, name + ".wgsl");
    if (existsSync(ov)) {
      out.wgsl = readFileSync(ov, "utf8");
      out.overridden = true;
    }
  }

  if (!noReference) {
    const refMsl = run("spirv-cross", ["--msl", d + ".src.spv"]);
    let rendered = false;
    if (refMsl.ok) {
      writeFileSync(d + ".ref.msl", refMsl.r.stdout);
      // Same file on both ShaderCompare legs: _zioshade.ppm is then exactly the
      // reference render the proxy gate diffs against, same uniforms + texture.
      const sc = run(SC, [d + ".ref.msl", d + ".ref.msl", d + ".refrender"], {
        env: { ...process.env, SHADERCOMPARE_GALLERY_UNIFORMS: "1", SHADERCOMPARE_RES: String(RES) },
      });
      const ppm = d + ".refrender_zioshade.ppm";
      if (sc.ok && existsSync(ppm)) {
        try {
          out.ref = parsePpm(readFileSync(ppm, "utf8"));
          rendered = true;
        } catch { /* fall through to the degraded verdict */ }
      }
    }
    // A reference-leg failure must NOT drop the shader: the browser leg still
    // proves tint acceptance, so judge it by the weaker LIVE assertions instead
    // (counted; the verdict line is labeled WEAKER).
    if (!rendered) out.noref = refMsl.ok ? "refrender-failed" : "crossmsl-failed";
  }
  return out;
}

